def glyph_family(category: str, asset_id: str) -> int:
    overrides = {"frozen_burst": 0, "frozen_afterimage": 5, "absolute_zero_device": 0,
                 "accelerated_combo": 2, "accelerant_window": 0, "redline_injector": 10,
                 "void_contract": 4, "void_brink": 4, "paradox_beacon": 0,
                 "focused_draw": 9, "piercing_draw": 9, "mirror_seed": 1,
                 "rewind_salve": 7, "brittle_vitality": 7, "narrow_escape": 3,
                 "risk_step": 4, "codex_margin": 5, "efficient_inscription": 5,
                 "boss_rush": 8, "daily_boss": 0, "authored_challenges": 2,
                 "training": 1, "endless": 4}
    if asset_id in overrides:
        return overrides[asset_id]
    lowered = asset_id.lower()
    matches = []
    for tokens, family in _TOKEN_FAMILIES:
        for token in tokens:
            if token in lowered:
                matches.append((lowered.rfind(token), len(token), family))
    if matches:
        return max(matches)[2]
    kind = CONTENT_METADATA.get(category, {}).get(asset_id, {}).get("kind", "")
    return {"survival": 3, "healing": 7, "weapon": 2, "time": 0,
            "time_skill": 0, "economy": 6, "positioning": 4, "risk": 7,
            "eternity": 0, "ruin": 2, "steel": 3, "time_guardian": 3,
            "void_walker": 4, "primordial_knight": 2, "time_lord": 5}.get(kind, 6)


@lru_cache(maxsize=None)
def _content_variant(category: str, asset_id: str) -> int:
    identities = CONTENT_METADATA.get(category, {}) if category != "mode_art" else MODE_ART
    related = sorted(identity for identity in identities if glyph_family(category, identity) == glyph_family(category, asset_id))
    return related.index(asset_id)


def content_frame(category: str, asset_id: str, frame: int) -> Image.Image:
    """Draw semantic artifact families with distinct housings, proportions and trim."""
    image, draw = _canvas()
    primary, accent, highlight = _content_colors(category)
    shape = glyph_family(category, asset_id)
    variant = _content_variant(category, asset_id)
    form, fit, trim = variant % 3, (variant // 3) % 3, variant // 9
    wobble = (0, 1, 0, -1)[frame]
    ink, stone, muted = PALETTE["ink"], PALETTE["stone"], PALETTE["muted"]
    cx, cy = 16, 16 + wobble
    radius = 8 + fit
    if category in ("blessings", "talents"):
        draw.arc((3, 3, 28, 28), 30, 150, fill=PALETTE["brass"], width=1)
        draw.arc((3, 3, 28, 28), 210, 330, fill=PALETTE["edge"], width=1)
    if shape == 0:
        if form == 0:
            draw.ellipse((cx - radius - 1, cy - radius - 1, cx + radius + 1, cy + radius + 1), fill=ink)
            draw.ellipse((cx - radius, cy - radius, cx + radius, cy + radius), fill=primary)
            draw.ellipse((cx - radius + 2, cy - radius + 2, cx + radius - 2, cy + radius - 2), fill=stone)
        elif form == 1:
            draw.polygon([(7 - fit, 5), (25 + fit, 5), (21, 12), (19, cy), (22, 23), (25 + fit, 27), (7 - fit, 27), (11, 22), (13, cy), (11, 11)], fill=ink)
            draw.line([(9 - fit, 6), (23 + fit, 6)], fill=primary, width=2)
            draw.line([(9 - fit, 26), (23 + fit, 26)], fill=primary, width=2)
            draw.polygon([(11, 9), (21, 9), (16, 16), (12, 23), (20, 23)], fill=accent)
        else:
            draw.polygon([(16, 3), (24 + fit, 10), (25, 22), (16, 28), (7, 22), (8 - fit, 10)], fill=ink)
            draw.polygon([(16, 5), (22 + fit, 11), (22, 21), (16, 25), (10, 21), (10 - fit, 11)], fill=primary)
