def _atlas(frames: Iterable[Image.Image]) -> Image.Image:
    frames = list(frames)
    width, height = frames[0].size
    if len(frames) != FRAME_COUNT or any(frame.size != (width, height) for frame in frames):
        raise ValueError("Atlas frames must have matching dimensions and declared count")
    atlas = Image.new("RGBA", (width * FRAME_COUNT, height), (0, 0, 0, 0))
    for index, frame in enumerate(frames):
        atlas.paste(frame, (index * width, 0))
    return atlas


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _write_atlases(destination: Path, family: str, ids: tuple[str, ...], renderer) -> list[dict]:
    family_dir = destination / family
    family_dir.mkdir(parents=True, exist_ok=True)
    rows: list[dict] = []
    for asset_id in ids:
        path = family_dir / f"{asset_id}.png"
        atlas = _atlas(renderer(asset_id, frame) for frame in range(FRAME_COUNT))
        atlas.save(path)
        rows.append({
            "id": asset_id,
            "path": str(path.relative_to(destination)),
            "kind": family,
            "width": atlas.width,
            "height": atlas.height,
            "frame_width": atlas.width // FRAME_COUNT,
            "frame_height": atlas.height,
            "frame_count": FRAME_COUNT,
            "filter": "nearest",
            "sha256": _sha(path),
        })
    return rows


def _existing_inventory(root: Path, family: str, ids: tuple[str, ...], manifest_name: str, path_key: str = "path") -> list[dict]:
    manifest_path = root / family / manifest_name
    if not manifest_path.exists():
        return []
    source = json.loads(manifest_path.read_text())
    source_rows = source.get("assets", source.get("atlases", []))
    output: list[dict] = []
    for row in source_rows:
        asset_id = str(row.get("id", Path(str(row.get(path_key, ""))).stem))
        if ids and asset_id not in ids:
            continue
        relative = str(row[path_key])
        file_path = root / family / relative
        if not file_path.exists():
            continue
        output.append({
            "id": asset_id,
            "path": str(file_path.relative_to(root)),
            "kind": family,
            "source_manifest": str(manifest_path.relative_to(root)),
            "filter": row.get("filter", "nearest"),
            "sha256": _sha(file_path),
        })
    return output


def _content_ids() -> dict[str, tuple[str, ...]]:
    result: dict[str, tuple[str, ...]] = {}
